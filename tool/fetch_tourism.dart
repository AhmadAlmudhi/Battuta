// Fetches international tourist arrivals from the World Bank and writes them
// as Dart for Explore's Most visited order (FR-EXP-08, PRD section 8.8).
//
// Usage: dart run tool/fetch_tourism.dart
//
// One request, with no key and no REST Countries quota. Takes each dataset
// country's most recent figure (see world_bank_tourism.dart), so run
// tool/fetch_snapshot.dart first if the dataset changed. Exits with an error,
// writing nothing, when the response doesn't parse or covers too few
// countries.
import 'dart:convert';
import 'dart:io';

import 'package:battuta/features/countries/data/country_parser.dart';
import 'package:battuta/features/countries/data/world_bank_tourism.dart';

const _snapshotPath = 'assets/data/countries_snapshot.json';
const _outputPath = 'lib/features/countries/data/tourism_arrivals.dart';

/// 198 of the 249 dataset countries have a figure today; far fewer means
/// the response changed shape.
const _minimumCountries = 150;

Future<void> main() async {
  final snapshot =
      jsonDecode(File(_snapshotPath).readAsStringSync())
          as Map<String, Object?>;
  final codes = {
    for (final record in snapshot['objects'] as List<Object?>)
      ?parseCountry(record as Map<String, Object?>)?.code,
  };

  final client = HttpClient()..connectionTimeout = const Duration(seconds: 15);
  final String body;
  try {
    final uri = Uri.parse(
      worldBankArrivalsUrl,
    ).replace(queryParameters: worldBankArrivalsQuery(DateTime.now().year));
    final response = await (await client.getUrl(uri)).close();
    body = await response.transform(utf8.decoder).join();
    if (response.statusCode != 200) {
      stderr.writeln('Request failed (${response.statusCode}): $body');
      exit(1);
    }
  } finally {
    client.close();
  }

  // A list of the paging details and the records; an error is one object.
  final decoded = jsonDecode(body);
  if (decoded is! List || decoded.length < 2 || decoded[1] is! List) {
    stderr.writeln('Unexpected response: $body');
    exit(1);
  }
  final latest = latestArrivals(decoded[1] as List<Object?>, codes);
  if (latest.length < _minimumCountries) {
    stderr.writeln(
      'Only ${latest.length} countries have figures; expected at least '
      '$_minimumCountries.',
    );
    exit(1);
  }

  final years = [for (final figure in latest.values) figure.year];
  final first = years.reduce((a, b) => a < b ? a : b);
  final last = years.reduce((a, b) => a > b ? a : b);
  final ranked = latest.entries.toList()
    ..sort((a, b) => b.value.arrivals.compareTo(a.value.arrivals));
  final source = StringBuffer()
    ..writeln('// Generated by tool/fetch_tourism.dart; do not edit by hand.')
    ..writeln('//')
    ..writeln('// International tourist arrivals, each country\'s most recent')
    ..writeln('// figure from $first to $last, from the World Bank\'s World')
    ..writeln('// Development Indicators (UN Tourism data, CC BY 4.0). They')
    ..writeln('// order Explore by Most visited (FR-EXP-08, PRD section 8.8).')
    ..writeln()
    ..writeln('/// Arrivals by 3-letter country code, most first. Countries')
    ..writeln('/// without a figure are left out.')
    ..writeln('const tourismArrivals = <String, int>{');
  for (final MapEntry(key: code, value: figure) in ranked) {
    source.writeln("  '$code': ${figure.arrivals},");
  }
  source.writeln('};');
  await File(_outputPath).writeAsString(source.toString());
  stdout.writeln(
    'Wrote ${latest.length} of ${codes.length} countries ($first to $last) '
    'to $_outputPath',
  );
}
